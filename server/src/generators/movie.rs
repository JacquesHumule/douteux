/// Turn a human title into scene-release-name casing, e.g.
/// `"No Country for Old Men"` -> `"No.Country.for.Old.Men"`.
fn normalize_title(title: &str) -> String {
    title
        .split_whitespace()
        .map(|word| {
            word.chars()
                .filter(|c| c.is_alphanumeric())
                .collect::<String>()
        })
        .filter(|w| !w.is_empty())
        .collect::<Vec<_>>()
        .join(".")
}

/// Generate a fake torrent-style movie release name.
pub fn generate() -> String {
    let mut rng = Rng::new();

    let (title, year) = *rng.pick(MOVIES);
    let title = normalize_title(title);

    let language = rng.pick(LANGUAGES);
    let resolution = rng.pick(RESOLUTIONS);
    let source = rng.pick(SOURCES);
    let audio = rng.pick(AUDIO);
    let codec = rng.pick(CODECS);
    let group = rng.pick(GROUPS);
    let ext = rng.pick(EXTENSIONS);
    // CRC32-style tag, like fansub releases — also keeps slugs from colliding.
    let hash = rng.hex(8);

    format!("{title}.{year}.{language}.{resolution}.{source}.{audio}.{codec}-{group}[{hash}].{ext}")
}
